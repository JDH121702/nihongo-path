export const kanjiLessons: KanjiLesson[] = [
  ...curatedKanjiLessons,
  ...joyoRemainderLessons,
];

export function getKanjiLesson(id: string) {
  return kanjiLessons.find((l) => l.id === id);
}

export function getAllKanjiLessonIds() {
  return kanjiLessons.map((l) => l.id);
}

let kanjiByCharacter: Map<string, KanjiEntry> | null = null;

export function getKanjiEntry(character: string) {
  if (!kanjiByCharacter) {
    kanjiByCharacter = new Map();
    for (const lesson of kanjiLessons) {
      for (const k of lesson.kanji) {
        if (!kanjiByCharacter.has(k.character)) {
          kanjiByCharacter.set(k.character, k);
        }
      }
    }
  }
  return kanjiByCharacter.get(character);
}
