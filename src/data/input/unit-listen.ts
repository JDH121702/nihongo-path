export function getUnitListenPack(unit: number) {
  return unitListenPacks.find((p) => p.unit === unit);
}

export function getAllUnitListenItems() {
  return unitListenPacks.flatMap((p) =>
    p.items.map((item) => ({ ...item, unit: p.unit })),
  );
}

export function unitListenStats() {
  const items = getAllUnitListenItems();
  return {
    packs: unitListenPacks.length,
    items: items.length,
    unitsCovered: speakingUnits.filter((u) =>
      unitListenPacks.some((p) => p.unit === u.id),
    ).length,
  };
}
